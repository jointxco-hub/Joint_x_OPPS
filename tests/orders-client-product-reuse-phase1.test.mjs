import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

async function readSource(relativePath) {
  const raw = await readFile(new URL(`../${relativePath}`, import.meta.url), "utf8");
  return raw.replace(/\r\n/g, "\n");
}

const EDITOR = "src/components/orders/drawer/ProductsEditor.jsx";
const API = "src/api/xosClientProduct.js";
const LINE_CONFIG = "src/features/orders/lineConfiguration.js";
const INVOICE_MAPPER = "src/features/invoices/orderToInvoiceItems.js";

// ─────────────────────────────────────────────────────────────────────
// ORDERS CLIENT-PRODUCT REUSE — PHASE 1. One unified add flow: the
