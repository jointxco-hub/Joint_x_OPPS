test("the composed-add flow reuses resolveComposition + writeAttachSnapshots - the EXACT same functions beginAttach/confirmAttach use, never a second copy", async () => {
  const src = await readSource(EDITOR);
  // beginAttach must now delegate to resolveComposition, not inline the old logic
  const beginAttachStart = src.indexOf("const beginAttach = async (lineId, clientProductId, orderLine) => {");
  const beginAttachBody = src.slice(beginAttachStart, src.indexOf("\n  };", beginAttachStart));
  assert.ok(beginAttachBody.includes("await resolveComposition(lineId, clientProductId, orderLine)"));

  // confirmAttach must delegate to writeAttachSnapshots
  const confirmAttachStart = src.indexOf("const confirmAttach = useMutation({");
  const confirmAttachBody = src.slice(confirmAttachStart, confirmAttachStart + 200);
  assert.ok(confirmAttachBody.includes("writeAttachSnapshots(pendingResolution)"));

  // the composed-add mutation must call the SAME two functions, not reimplement them
  const composedStart = src.indexOf("const addComposedClientProductMutation = useMutation({");
  const composedBody = src.slice(composedStart, src.indexOf("onSuccess: ({ replayed", composedStart));
  assert.ok(composedBody.includes("await resolveComposition(parentLineId, clientProductId,"));
  assert.ok(composedBody.includes("await writeAttachSnapshots(result)"));
  assert.ok(!composedBody.includes("OrderLineComponentSnapshot.create("), "must not re-implement snapshot creation inline - only writeAttachSnapshots may call .create()");
});

